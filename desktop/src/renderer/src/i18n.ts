export type Lang = 'en'

let currentLang: Lang = 'en'

export function t(key: string): string {
  return translations.en?.[key] || key
}

/** {@link t} with simple `{placeholder}` interpolation. */
export function tf(key: string, vars: Record<string, string | number>): string {
  let out = t(key)
  for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v))
  return out
}

export function getLang(): Lang {
  return currentLang
}

export function setLang(_lang: Lang) {
  currentLang = 'en'
}

/** Resolve a possibly-localized label ({zh,en} or plain string) for the current language. */
export function localizedLabel(label: string | { en: string; zh?: string } | undefined): string {
  if (!label) return ''
  if (typeof label === 'string') return label
  return label.en || ''
}
